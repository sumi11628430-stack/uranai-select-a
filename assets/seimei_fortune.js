function seimeiKindPoint(kind) {
  return { "大吉": 5, "吉": 4, "半吉": 3, "凶": 2, "大凶": 1 }[kind] || 3;
}
function seimeiStars(score) {
  return '<span class="unsei-stars" aria-label="5段階中' + score + '">' +
           '★★★★★'.slice(0, score) + '<span class="off">' + '★★★★★'.slice(0, 5 - score) + '</span>' +
         '</span>';
}

/* g = { tenkaku, jinkaku, chikaku, gaikaku, soukaku, sokokuCount(三才の相剋の数), jinGogyo } */
function seimeiUnseiScores(g) {
  var p = function (n) { return seimeiKindPoint(kakusuInfo(n).kind); };
  var mix = function (a, b) { return Math.max(1, Math.min(5, Math.round(a * 0.6 + b * 0.4))); };
  var sansai = g.sokokuCount === 0 ? 5 : (g.sokokuCount === 1 ? 3 : 2);
  return {
    sogo:    mix(p(g.jinkaku), p(g.soukaku)),
    kin:     mix(p(g.jinkaku), p(g.soukaku)),
    ren:     mix(p(g.jinkaku), p(g.chikaku)),
    ken:     mix(sansai, p(g.jinkaku)),
    shigoto: mix(p(g.jinkaku), p(g.gaikaku)),
    gaku:    mix(p(g.chikaku), p(g.jinkaku)),
    shobu:   mix(p(g.soukaku), p(g.gaikaku)),
    kekkon:  mix(p(g.chikaku), p(g.soukaku)),
    taijin:  mix(p(g.gaikaku), p(g.jinkaku))
  };
}

function seimeiUnseiHTML(g) {
  var sc = seimeiUnseiScores(g);
  var cards = SEIMEI_UNSEI.map(function (c) {
    return '<div class="f-sec unsei-card">' +
             '<h3>' + c.icon + ' ' + c.label + seimeiStars(sc[c.key]) + '</h3>' +
             '<p>' + c.texts[sc[c.key]] + '</p>' +
             '<p class="unsei-basis">鑑定のもと：' + c.basis + '</p>' +
           '</div>';
  }).join("");

  var t = SEIMEI_TALENT[g.jinGogyo];
  var talent =
    '<div class="f-sec unsei-wide">' +
      '<h3>🌟 才能・適職<span class="unsei-sub">人格の五行「' + g.jinGogyo + '」</span></h3>' +
      '<p><b class="unsei-gift">' + t.gift + '</b>　' + t.text + '</p>' +
      '<div class="unsei-jobs">' + t.jobs.map(function (j) { return '<span>' + j + '</span>'; }).join("") + '</div>' +
    '</div>';

  // 最も★が低い分類を「意識したい運」として開運アドバイスに添える（同点は表示順で先のもの）
  var weakest = SEIMEI_UNSEI[0];
  SEIMEI_UNSEI.forEach(function (c) { if (sc[c.key] < sc[weakest.key]) weakest = c; });
  var L = SEIMEI_LUCK[g.jinGogyo];
  var advice =
    '<div class="f-sec advice unsei-wide">' +
      '<h3>✨ 開運アドバイス</h3>' +
      '<p>今のあなたが意識したいのは「' + weakest.label + '」。' + weakest.tip + 'が、運気の底上げにつながります。</p>' +
      '<div class="lucky-row" style="margin-top:.8rem;">' +
        '<span class="lucky-chip"><b>ラッキーカラー</b>' + L.color + '</span>' +
        '<span class="lucky-chip"><b>ラッキーナンバー</b>' + L.number + '</span>' +
        '<span class="lucky-chip"><b>吉方位</b>' + L.dir + '</span>' +
        '<span class="lucky-chip"><b>開運アイテム</b>' + L.item + '</span>' +
        '<span class="lucky-chip"><b>開運アクション</b>' + L.action + '</span>' +
      '</div>' +
    '</div>';

  return '<div class="fortune-sections unsei-grid">' + cards + talent + advice + '</div>';
}

